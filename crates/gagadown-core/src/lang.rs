//! Minimal bilingual UI strings: Simplified Chinese plus English.
//!
//! Call sites keep the Chinese literal as the lookup key — `tr("下载")` —
//! so the diff stays mechanical. `tr` returns the Chinese text on zh
//! locales and the English entry on any other locale; missing entries
//! fall back to the key itself, so the table can grow incrementally.

use serde::{Deserialize, Serialize};
use std::sync::OnceLock;
use std::sync::atomic::{AtomicU8, Ordering};

#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum Lang {
    Zh,
    En,
}

/// Persisted language preference (`Settings::language`); `Auto` follows the
/// system locale.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "lowercase")]
pub enum LangPref {
    #[default]
    Auto,
    Zh,
    En,
}

static DETECTED: OnceLock<Lang> = OnceLock::new();
/// 0 = follow system, 1 = zh, 2 = en.
static PREF: AtomicU8 = AtomicU8::new(0);

fn detected() -> Lang {
    *DETECTED.get_or_init(|| match sys_locale::get_locale() {
        Some(l) if l.to_lowercase().starts_with("zh") => Lang::Zh,
        _ => Lang::En,
    })
}

/// Apply a preference change; takes effect on the next `tr`/`trf` call.
pub fn set_pref(pref: LangPref) {
    let v = match pref {
        LangPref::Auto => 0,
        LangPref::Zh => 1,
        LangPref::En => 2,
    };
    PREF.store(v, Ordering::Relaxed);
}

pub fn lang() -> Lang {
    match PREF.load(Ordering::Relaxed) {
        1 => Lang::Zh,
        2 => Lang::En,
        _ => detected(),
    }
}

/// Translate a user-facing string. `zh` doubles as the lookup key.
pub fn tr(zh: &'static str) -> &'static str {
    match lang() {
        Lang::Zh => zh,
        Lang::En => en(zh),
    }
}

/// Translate a template and substitute `{0}`, `{1}`, … with the matching
/// `args` entry, so English word order may differ from the Chinese key.
/// Pre-render non-`Display` formatting (e.g. `format!("{:.1}", v)`) and
/// pass the result — `{i:spec}` is not supported.
pub fn trf(zh: &'static str, args: &[&dyn std::fmt::Display]) -> String {
    let mut s = tr(zh).to_string();
    for (i, a) in args.iter().enumerate() {
        let indexed = format!("{{{i}}}");
        if s.contains(&indexed) {
            s = s.replace(&indexed, &a.to_string());
        } else {
            s = s.replacen("{}", &a.to_string(), 1);
        }
    }
    s
}

