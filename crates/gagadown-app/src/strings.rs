//! English translations for the app UI. Call sites keep the Chinese literal
//! as the lookup key — `tr("下载")` — so the diff stays mechanical. `tr`
//! returns the Chinese text on zh locales and the English entry on any other
//! locale; missing entries fall back to the key itself.

use gagadown_core::lang::{lang, Lang};

/// Translate a user-facing string. `zh` doubles as the lookup key.
pub fn tr(zh: &'static str) -> &'static str {
    match lang() {
        Lang::Zh => zh,
        Lang::En => en(zh),
    }
}

/// `tr` for format templates: `{}` placeholders are filled in order, and
/// `{0}`/`{1}` style indices are honoured so English may reorder arguments.
/// (`format!` itself requires a literal template, hence this helper.)
pub fn trf(zh: &'static str, args: &[&dyn std::fmt::Display]) -> String {
    let mut out = tr(zh).to_string();
    for (i, arg) in args.iter().enumerate() {
        let indexed = format!("{{{i}}}");
        if out.contains(&indexed) {
            out = out.replace(&indexed, &arg.to_string());
        } else {
            out = out.replacen("{}", &arg.to_string(), 1);
        }
    }
    out
}

